-- Patch 010: จัดลำดับแผนก (sort_order) ใหม่ให้เป็นเลขเรียงติดกันไม่ซ้ำกันเลย
-- ============================================================================
-- ปัญหาที่เจอ: patch_007 สร้างแผนกที่มีอยู่จริงในข้อมูลเดิมขึ้นมาโดยอัตโนมัติ
-- ทุกแผนกได้ sort_order = 0 เหมือนกันหมด (ค่าเริ่มต้น) ส่วน patch_008 ตั้งลำดับ
-- ให้เฉพาะ 11 รหัสที่ระบุไว้ (LB, EVI, ... LOAD) แผนกอื่นๆ ที่เหลือ (ซึ่งอาจเป็น
-- แผนกที่มีคนจริงอยู่) เลยยังค้างอยู่ที่ 0 เท่ากันหมด — ปุ่ม ↑/↓ ที่ "สลับค่า"
-- ระหว่าง 2 แผนกที่ค่าเท่ากันอยู่แล้ว (0 กับ 0) จึงดูเหมือนไม่มีอะไรเกิดขึ้นเลย
--
-- Patch นี้ไล่กำหนดเลขลำดับใหม่ให้ทุกแผนก "ไม่ซ้ำกันเลยสักคู่" โดย:
--   - 11 รหัสที่เคยระบุไว้ใน patch_008 ยังคงอยู่ตำแหน่งเดิม (1-11)
--   - แผนกอื่นๆ ที่เหลือ เรียงต่อจากนั้นตามตัวอักษร (แก้ลำดับใหม่ได้ทีหลังในแอป)
-- หลังรัน patch นี้ ปุ่ม ↑/↓ ในแอปจะเห็นผลชัดเจนทุกครั้ง (โค้ดฝั่งเว็บก็แก้ให้
-- เขียนเลขลำดับใหม่ทั้งหมดทุกครั้งที่กดแล้ว กันปัญหานี้เกิดซ้ำในอนาคตด้วย)
-- ============================================================================

with ordered as (
  select
    dept_key,
    row_number() over (
      order by
        case dept_key
          when 'LB' then 1 when 'EVI' then 2 when 'CHI' then 3 when 'OH' then 4
          when 'CUT-UP' then 5 when 'SC' then 6 when 'SMP-IVQF' then 7 when 'PACK' then 8
          when 'FREEZE' then 9 when 'CS' then 10 when 'LOAD' then 11
          else 1000
        end,
        dept_key
    ) - 1 as new_order
  from departments
)
update departments d
set sort_order = o.new_order
from ordered o
where o.dept_key = d.dept_key;

-- ตรวจสอบผลลัพธ์ (ควรเห็นเลขเรียง 0,1,2,3... ไม่ซ้ำกันเลยสักคู่)
select dept_key, label, sort_order from departments order by sort_order;
