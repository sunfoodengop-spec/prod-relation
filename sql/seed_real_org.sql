-- ขั้นที่ 1: Upsert ข้อมูลพนักงานทั้งหมด (ยังไม่ผูก supervisor_id)
insert into users (emp_code, password_hash, first_name, last_name, nickname, position_title, department, org_level, role)
select emp_code, crypt(emp_code, gen_salt('bf')), first_name, last_name, nickname, position_title, department, org_level, role
from org_staging
on conflict (emp_code) do update set
    first_name     = excluded.first_name,
    last_name      = excluded.last_name,
    nickname       = excluded.nickname,
    position_title = excluded.position_title,
    department     = excluded.department,
    org_level      = excluded.org_level,
    role           = excluded.role;

-- ขั้นที่ 2: ผูกสายบังคับบัญชา (supervisor_id) ตาม emp_code ในผัง
update users u
set supervisor_id = sup.user_id
from org_staging s
join users sup on sup.emp_code = s.supervisor_emp_code
where u.emp_code = s.emp_code and s.supervisor_emp_code is not null;

-- ตรวจสอบผลลัพธ์
select emp_code, first_name, last_name, position_title, org_level, role,
       (select first_name || ' ' || last_name from users s where s.user_id = u.supervisor_id) as supervisor_name
from users u
where emp_code in (select emp_code from org_staging)
order by org_level desc, department, first_name;
